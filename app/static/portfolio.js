/* ==========================================================
   Portfolio (rework) — native in-SPA portfolio monitoring.

   Roster comes from the Drive folder (one subfolder = one company); each
   company's update is produced by a two-pass LLM over its ingested documents
   + Granola notes, in the firm's derisking + traction format.

   Two views: Dashboard (totals + attention + holdings) and Company
   ("since we invested": AI update, traction, derisking trend w/ evidence,
   the document corpus, notes). Loads after app.js so it can reuse the host
   auth (_rvmHeaders) and hook switchTab.
   ========================================================== */
(function () {
  const API = '/api/portfolio-review';

  function headers() {
    return (typeof window._rvmHeaders === 'function')
      ? window._rvmHeaders() : { 'Content-Type': 'application/json' };
  }
  async function getJSON(url) {
    const r = await fetch(url, { headers: headers(), cache: 'no-store' });
    if (r.status === 401) throw new Error('unauthorized');
    if (!r.ok) throw new Error('HTTP ' + r.status);
    return r.json();
  }
  async function postJSON(url) {
    const r = await fetch(url, { method: 'POST', headers: headers() });
    const body = await r.json().catch(() => ({}));
    if (!r.ok) throw new Error(body.detail || ('HTTP ' + r.status));
    return body;
  }
  function root() { return document.getElementById('portfolio-root'); }

  // ── formatting ───────────────────────────────────────────────────────────
  function esc(s) {
    return String(s == null ? '' : s).replace(/[&<>"']/g, c => (
      { '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
  }
  function money(v) {
    if (v == null || isNaN(v)) return '—';
    const a = Math.abs(v), sign = v < 0 ? '-' : '';
    if (a >= 1e9) return sign + '$' + (a / 1e9).toFixed(2) + 'B';
    if (a >= 1e6) return sign + '$' + (a / 1e6).toFixed(a / 1e6 >= 10 ? 1 : 2) + 'M';
    if (a >= 1e3) return sign + '$' + (a / 1e3).toFixed(0) + 'K';
    return sign + '$' + a.toFixed(0);
  }
  function mult(v) { return (v == null || isNaN(v)) ? '—' : v.toFixed(2) + 'x'; }
  function months(v) { return (v == null || isNaN(v)) ? '—' : Math.round(v) + ' mo'; }
  function signedPct(v) {
    if (v == null || isNaN(v)) return '—';
    const p = Math.round(v * 100);
    return (p > 0 ? '+' : p < 0 ? '−' : '') + Math.abs(p) + '%';
  }
  function varClass(v) {
    if (v == null) return 'pf-muted';
    if (v <= -0.05) return 'pf-neg';
    if (v >= 0.05) return 'pf-pos';
    return 'pf-flat';
  }
  function dateShort(s) { return s ? String(s).slice(0, 10) : ''; }
  function quartileBadge(q, exited) {
    if (exited) return '<span class="pf-q pf-q-exit">Exited</span>';
    if (q == null) return '<span class="pf-muted">—</span>';
    return `<span class="pf-q pf-q${q}">Q${q}</span>`;
  }
  function isAdmin() {
    try { return (window._rvmUser && window._rvmUser.role === 'admin'); } catch (e) { return false; }
  }

  // ── DASHBOARD ─────────────────────────────────────────────────────────────
  async function renderDashboard() {
    const el = root();
    el.innerHTML = '<div class="pf-loading">Loading portfolio…</div>';
    let data, me;
    try {
      [data, me] = await Promise.all([
        getJSON(`${API}/overview`),
        getJSON('/api/auth/me').catch(() => null),
      ]);
    } catch (e) { el.innerHTML = errorState(e); return; }
    const admin = !!(me && me.role === 'admin');

    const t = data.totals || {};
    const kpis = [
      ['Companies', t.n_companies != null ? t.n_companies : '—'],
      ['Reviewed', `${t.n_reviewed || 0} / ${t.n_companies || 0}`],
      ['Documents', (t.n_docs || 0).toLocaleString()],
      ['Open flags', t.n_flags != null ? t.n_flags : '—'],
    ];
    const kpiHtml = kpis.map(([k, v]) => `
      <div class="pf-kpi"><div class="pf-kpi-label">${k}</div><div class="pf-kpi-value">${v}</div></div>`).join('');

    el.innerHTML = `
      <div class="pf-head">
        <div>
          <h1 class="pf-title">Portfolio</h1>
          <p class="pf-sub">Roster synced from the portfolio Drive folder. Each company's update is generated by an LLM over its documents + meeting notes.</p>
        </div>
      </div>
      <div class="pf-kpis">${kpiHtml}</div>
      ${adminToolbar(admin)}
      ${attentionStrip(data.attention || [])}
      ${holdingsTable(data.holdings || [])}
    `;
    el.onclick = (e) => {
      const node = e.target.closest('[data-company]');
      if (node && el.contains(node)) renderCompany(Number(node.dataset.company));
    };
    if (admin) wireAdmin();
  }

  // ── admin ingestion controls ──────────────────────────────────────────────
  function adminToolbar(admin) {
    if (!admin) return '';
    return `<div class="pf-card pf-admin">
      <div class="pf-admin-row">
        <div class="pf-admin-info">
          <strong>Ingestion</strong>
          <span class="pf-dim"> — roster + documents from the portfolio Drive folder &amp; Granola.</span>
          <span id="pf-drive-status" class="pf-tiny pf-dim"> Checking Drive…</span>
        </div>
        <div class="pf-admin-btns">
          <a class="pf-btn pf-btn-ghost pf-hidden" id="pf-connect" target="_blank" rel="noopener">Connect Drive</a>
          <button class="pf-btn" id="pf-sync">Sync from Drive + Granola</button>
          <button class="pf-btn pf-btn-ghost" id="pf-genall">Generate all updates</button>
        </div>
      </div>
      <div id="pf-admin-msg"></div>
    </div>`;
  }

  async function wireAdmin() {
    const status = document.getElementById('pf-drive-status');
    const connect = document.getElementById('pf-connect');
    const token = localStorage.getItem('rvm_token') || '';
    try {
      const cs = await getJSON('/api/drive/connection-status');
      if (cs && cs.connected) {
        if (status) status.textContent = ` Drive connected${cs.google_email ? ' · ' + cs.google_email : ''}.`;
        if (connect) connect.classList.add('pf-hidden');
      } else {
        if (status) status.textContent = ' Drive not connected.';
        if (connect) {
          connect.href = `/api/drive/oauth/authorize?token=${encodeURIComponent(token)}`;
          connect.classList.remove('pf-hidden');
        }
      }
    } catch (e) { if (status) status.textContent = ''; }
    const sync = document.getElementById('pf-sync');
    if (sync) sync.addEventListener('click', adminSync);
    const genall = document.getElementById('pf-genall');
    if (genall) genall.addEventListener('click', adminGenAll);
  }

  async function adminSync() {
    const msg = document.getElementById('pf-admin-msg');
    const btn = document.getElementById('pf-sync');
    btn.disabled = true; const t = btn.textContent; btn.textContent = 'Syncing…';
    msg.innerHTML = `<div class="pf-gen-busy"><span class="pf-spin"></span> Discovering companies, pulling Granola, extracting documents…</div>`;
    try {
      const r = await postJSON(`${API}/sync-all`);
      const d = r.discover || {}, tot = r.totals || {};
      msg.innerHTML = `<div class="pf-ok pf-tiny">Synced ${d.companies_created || 0} new / ${d.companies_updated || 0} existing companies · ${tot.documents_upserted || 0} documents · ${tot.granola_docs || 0} notes.</div>`;
      setTimeout(renderDashboard, 1200);
    } catch (e) {
      btn.disabled = false; btn.textContent = t;
      msg.innerHTML = `<div class="pf-gen-err">Sync failed: ${esc(e.message)}</div>`;
    }
  }

  async function adminGenAll() {
    if (!confirm('Generate AI updates for every company with documents? Runs the LLM sequentially — can take several minutes.')) return;
    const msg = document.getElementById('pf-admin-msg');
    const btn = document.getElementById('pf-genall');
    btn.disabled = true; const t = btn.textContent; btn.textContent = 'Generating…';
    msg.innerHTML = `<div class="pf-gen-busy"><span class="pf-spin"></span> Generating updates across the portfolio…</div>`;
    try {
      const r = await postJSON(`${API}/generate-all`);
      msg.innerHTML = `<div class="pf-ok pf-tiny">Generated ${r.generated || 0} updates${(r.errors && r.errors.length) ? ` · ${r.errors.length} failed` : ''}.</div>`;
      setTimeout(renderDashboard, 1200);
    } catch (e) {
      btn.disabled = false; btn.textContent = t;
      msg.innerHTML = `<div class="pf-gen-err">Generate-all failed: ${esc(e.message)}</div>`;
    }
  }

  function attentionStrip(flags) {
    if (!flags.length) {
      return `<div class="pf-card pf-attention pf-attention-empty">
        <span class="pf-dot pf-dot-pos"></span> Nothing flagged — no runway, revenue-decline, mark-down or derisking alerts.</div>`;
    }
    const items = flags.slice(0, 14).map(f => `
      <button class="pf-flag pf-flag-${esc(f.level)}" data-company="${f.company_id}">
        <span class="pf-dot pf-dot-${esc(f.level)}"></span>
        <span class="pf-flag-co">${esc(f.company_name)}</span>
        <span class="pf-flag-label">${esc(f.label)}</span>
      </button>`).join('');
    return `<div class="pf-card pf-attention">
        <div class="pf-card-title">Needs attention <span class="pf-count">${flags.length}</span></div>
        <div class="pf-flags">${items}</div></div>`;
  }

  function holdingsTable(rows) {
    if (!rows.length) {
      return `<div class="pf-card"><div class="pf-empty">No portfolio companies yet. Run <strong>Discover companies</strong> to sync the roster from Drive.</div></div>`;
    }
    const body = rows.map(h => {
      const flagBadge = h.n_flags
        ? `<span class="pf-rowflag pf-rowflag-${h.top_flag_level}">${h.n_flags}</span>` : '';
      const reviewed = h.reviewed
        ? `<span class="pf-ok" title="${esc(dateShort(h.last_update_at))}">${esc((h.headline || 'Reviewed')).slice(0, 60)}</span>`
        : `<span class="pf-muted">Not yet reviewed</span>`;
      const growth = h.revenue_growth_pct == null ? '<span class="pf-muted">—</span>'
        : `<span class="${varClass(h.revenue_growth_pct)}">${signedPct(h.revenue_growth_pct)}</span>`;
      return `
        <tr data-company="${h.id}">
          <td class="pf-co"><span>${esc(h.name)}</span>${flagBadge}</td>
          <td>${esc(h.fund || '—')}</td>
          <td class="pf-dim">${esc(h.commercial_status || '—')}</td>
          <td class="pf-num">${money(h.revenue_current)}</td>
          <td class="pf-num">${growth}</td>
          <td class="pf-num">${months(h.runway_months)}</td>
          <td class="pf-center">${quartileBadge(h.derisk_quartile)}</td>
          <td class="pf-review">${reviewed}</td>
        </tr>`;
    }).join('');
    return `<div class="pf-card">
        <div class="pf-card-title">Holdings</div>
        <table class="pf-table">
          <thead><tr>
            <th>Company</th><th>Fund</th><th>Status</th>
            <th class="pf-num">Revenue</th><th class="pf-num">YoY</th><th class="pf-num">Runway</th>
            <th class="pf-center">Derisk</th><th>Latest update</th>
          </tr></thead>
          <tbody>${body}</tbody>
        </table></div>`;
  }

  // ── COMPANY DETAIL ────────────────────────────────────────────────────────
  async function renderCompany(id) {
    const el = root();
    el.innerHTML = '<div class="pf-loading">Loading company…</div>';
    let d;
    try { d = await getJSON(`${API}/company/${id}/full`); }
    catch (e) { el.innerHTML = errorState(e); return; }

    const c = d.company || {};
    const der = d.derisking || [];
    const latestQ = der.length ? der[der.length - 1] : {};
    const sub = [c.sector, c.fund, (d.traction && d.traction.commercial_status) || c.commercial_status]
      .filter(Boolean).map(esc).join(' · ');

    el.innerHTML = `
      <button class="pf-back" id="pf-back">← Portfolio</button>
      <div class="pf-detail-head">
        <div>
          <h1 class="pf-title">${esc(c.name)}</h1>
          <p class="pf-sub">${sub || '—'}</p>
        </div>
        <div class="pf-detail-right">
          <div class="pf-detail-q">${quartileBadge(latestQ.quartile, latestQ.is_exited)}<div class="pf-kpi-label">derisking</div></div>
          <button class="pf-btn" id="pf-gen">${d.update ? 'Re-generate update' : 'Generate update'}</button>
        </div>
      </div>
      <div id="pf-gen-msg"></div>
      ${updateCard(d.update, d.evidence_gaps || [])}
      ${tractionCard(d.traction)}
      ${deriskingCard(d.dimensions || [], der, d.latest_reasoning || {})}
      ${documentsCard(d.documents || [])}
      <div class="pf-grid2">
        ${notesCard(d.notes || [])}
        ${governanceCard(d.investments || [], d.board_seats || [], d.returns || [])}
      </div>
    `;
    document.getElementById('pf-back').addEventListener('click', renderDashboard);
    document.getElementById('pf-gen').addEventListener('click', () => generate(id));
  }

  async function generate(id) {
    const btn = document.getElementById('pf-gen');
    const msg = document.getElementById('pf-gen-msg');
    btn.disabled = true; const label = btn.textContent;
    btn.textContent = 'Generating…';
    msg.innerHTML = `<div class="pf-card pf-gen-busy"><span class="pf-spin"></span> Reading documents + notes and writing the update… this takes ~20–60s.</div>`;
    try {
      await postJSON(`${API}/company/${id}/generate-update`);
      await renderCompany(id);
    } catch (e) {
      btn.disabled = false; btn.textContent = label;
      msg.innerHTML = `<div class="pf-card pf-gen-err">Couldn't generate update: ${esc(e.message)}</div>`;
    }
  }

  function updateCard(u, gaps) {
    if (!u) {
      return `<div class="pf-card pf-update pf-update-off">
        <div class="pf-card-title">AI update</div>
        <div class="pf-empty">No update generated yet. Click <strong>Generate update</strong> to have the model read this company's documents + notes and produce a structured review.</div>
      </div>`;
    }
    const gapHtml = gaps.length
      ? `<div class="pf-gaps"><span class="pf-gaps-label">Evidence gaps:</span> ${gaps.map(g => `<span class="pf-gap">${esc(g)}</span>`).join(' ')}</div>` : '';
    return `<div class="pf-card pf-update">
      <div class="pf-card-title">AI update
        <span class="pf-card-note">${esc(u.model_used || '')} · read ${u.n_docs_used}/${u.n_docs_seen} docs · ${esc(dateShort(u.created_at))}</span>
      </div>
      ${u.headline ? `<div class="pf-headline">${esc(u.headline)}</div>` : ''}
      ${u.summary ? `<p class="pf-update-sum">${esc(u.summary)}</p>` : ''}
      ${gapHtml}
    </div>`;
  }

  function tractionCard(tr) {
    if (!tr) {
      return `<div class="pf-card"><div class="pf-card-title">Traction</div><div class="pf-empty">No traction snapshot yet.</div></div>`;
    }
    const facts = [
      ['Status', tr.commercial_status],
      ['Revenue', money(tr.revenue_current)],
      ['Prior', money(tr.revenue_prior)],
      ['YoY', tr.revenue_growth_pct != null ? signedPct(tr.revenue_growth_pct) : null],
      ['ARR', tr.arr_current != null ? money(tr.arr_current) : null],
      ['Customers', tr.customer_count],
      ['Runway', tr.runway_months != null ? months(tr.runway_months) : null],
      ['Raising', tr.fundraising_status],
      ['Confidence', tr.confidence],
    ].filter(([, v]) => v != null && v !== '')
      .map(([k, v]) => `<div class="pf-fact"><span>${esc(k)}</span><b>${esc(v)}</b></div>`).join('');
    return `<div class="pf-card">
      <div class="pf-card-title">Traction</div>
      <div class="pf-facts">${facts}</div>
      ${tr.notable_milestones ? `<p class="pf-blk"><b>Milestones.</b> ${esc(tr.notable_milestones)}</p>` : ''}
      ${tr.change_vs_baseline ? `<p class="pf-blk"><b>Since investment.</b> ${esc(tr.change_vs_baseline)}</p>` : ''}
    </div>`;
  }

  function deriskingCard(dims, history, reasoning) {
    if (!history.length) {
      return `<div class="pf-card"><div class="pf-card-title">Derisking</div><div class="pf-empty">No derisking scores yet.</div></div>`;
    }
    const cell = (v) => {
      if (v == null || v === '') return '<span class="pf-muted">·</span>';
      const n = Number(v);
      if (n > 0) return '<span class="pf-score pf-score-pos">+1</span>';
      if (n < 0) return '<span class="pf-score pf-score-neg">−1</span>';
      return '<span class="pf-score pf-score-zero">0</span>';
    };
    const head = `<th>Dimension</th>` + history.map(h =>
      `<th class="pf-center">${esc(h.period)}${h.evaluator === 'llm' ? ' <span class="pf-ai">AI</span>' : ''}</th>`).join('');
    const dimRows = dims.map(dim => {
      const cells = history.map(h => `<td class="pf-center">${cell(h[dim.key])}</td>`).join('');
      const r = reasoning[dim.key] || {};
      const why = r.reasoning
        ? `<div class="pf-why">${esc(r.reasoning)}${(r.evidence && r.evidence.length) ? ` <span class="pf-cite">[${r.evidence.map(e => esc(e)).join(', ')}]</span>` : ''}</div>` : '';
      return `<tr><td>${esc(dim.label)}${why}</td>${cells}</tr>`;
    }).join('');
    const totalRow = `<tr class="pf-total-row"><td>Total</td>` +
      history.map(h => `<td class="pf-center pf-strong">${h.total_score != null ? h.total_score : '—'}</td>`).join('') + `</tr>`;
    const quartRow = `<tr><td>Quartile</td>` +
      history.map(h => `<td class="pf-center">${quartileBadge(h.quartile, h.is_exited)}</td>`).join('') + `</tr>`;
    return `<div class="pf-card">
      <div class="pf-card-title">Derisking <span class="pf-card-note">7 dimensions · +1 derisked / −1 still a risk, relative to the IC thesis · [n] = source doc</span></div>
      <table class="pf-table pf-table-sm pf-derisk"><thead><tr>${head}</tr></thead>
      <tbody>${dimRows}${totalRow}${quartRow}</tbody></table>
    </div>`;
  }

  function documentsCard(docs) {
    if (!docs.length) {
      return `<div class="pf-card"><div class="pf-card-title">Documents</div><div class="pf-empty">No documents ingested. Run ingestion to pull this company's Drive folder + notes.</div></div>`;
    }
    const rows = docs.map(d => `
      <tr>
        <td class="pf-doc-id">[${d.id}]</td>
        <td>${d.source_url ? `<a href="${esc(d.source_url)}" target="_blank" rel="noopener">${esc(d.title || 'Untitled')}</a>` : esc(d.title || 'Untitled')}</td>
        <td class="pf-dim">${esc(d.doc_type || 'other')}</td>
        <td class="pf-dim">${esc(d.source)}</td>
        <td class="pf-dim">${esc(dateShort(d.occurred_at))}</td>
      </tr>`).join('');
    return `<div class="pf-card">
      <div class="pf-card-title">Document corpus <span class="pf-count">${docs.length}</span>
        <span class="pf-card-note">what the AI read · ids match the [n] citations above</span></div>
      <table class="pf-table pf-table-sm"><thead><tr><th>ID</th><th>Title</th><th>Type</th><th>Source</th><th>Date</th></tr></thead>
      <tbody>${rows}</tbody></table></div>`;
  }

  function notesCard(notes) {
    if (!notes.length) {
      return `<div class="pf-card"><div class="pf-card-title">Recent notes</div><div class="pf-empty">No linked meeting notes.</div></div>`;
    }
    const items = notes.map(n => `
      <div class="pf-note">
        <div class="pf-note-head">
          ${n.note_url ? `<a href="${esc(n.note_url)}" target="_blank" rel="noopener">${esc(n.note_title || 'Note')}</a>` : `<span>${esc(n.note_title || 'Note')}</span>`}
          <span class="pf-dim pf-tiny">${esc(dateShort(n.note_updated_at))}</span>
        </div>
        ${n.note_summary ? `<p class="pf-note-sum">${esc(String(n.note_summary).slice(0, 220))}</p>` : ''}
      </div>`).join('');
    return `<div class="pf-card"><div class="pf-card-title">Recent notes</div>${items}</div>`;
  }

  function governanceCard(investments, seats, returns) {
    const seatHtml = seats.length
      ? seats.map(s => `<div class="pf-fact"><span>${esc(s.seat_type)}</span><b>${esc(s.board_member)}</b></div>`).join('')
      : '<div class="pf-empty">No active board seats.</div>';
    const latest = returns.length ? returns[returns.length - 1] : null;
    const ret = latest ? `<div class="pf-facts pf-mt">
        <div class="pf-fact"><span>Cost</span><b>${money(latest.cost)}</b></div>
        <div class="pf-fact"><span>FMV</span><b>${money(latest.fmv)}</b></div>
        <div class="pf-fact"><span>MOIC</span><b>${mult(latest.multiple)}</b></div>
      </div>` : '';
    return `<div class="pf-card">
      <div class="pf-card-title">Governance &amp; position</div>
      <div class="pf-facts">${seatHtml}</div>${ret}
    </div>`;
  }

  function errorState(e) {
    if (String(e && e.message) === 'unauthorized') {
      return `<div class="pf-card"><div class="pf-empty">Please log in to view the portfolio.</div></div>`;
    }
    return `<div class="pf-card"><div class="pf-empty">Couldn't load portfolio data (${esc(e && e.message)}).</div></div>`;
  }

  // ── boot / switchTab hook ─────────────────────────────────────────────────
  let _rendered = false;
  function showPortfolio() {
    if (!root()) return;
    if (!_rendered) { _rendered = true; renderDashboard(); }
  }
  // Defensive: the portfolio module must never be able to break the host SPA.
  try {
    if (typeof window.switchTab === 'function') {
      const orig = window.switchTab;
      window.switchTab = function (tab) {
        orig.apply(this, arguments);
        try { if (tab === 'portfolio') showPortfolio(); } catch (e) { console.error('[portfolio]', e); }
      };
    }
    document.addEventListener('DOMContentLoaded', () => {
      try {
        const tab = document.getElementById('tab-portfolio');
        if (tab && tab.classList.contains('active')) showPortfolio();
      } catch (e) { console.error('[portfolio]', e); }
    });
  } catch (e) { console.error('[portfolio] init failed', e); }

  window.Portfolio = { dashboard: renderDashboard, company: renderCompany };
})();
